// Rebuild only the optional online core; the offline physics files are untouched.
import fs from 'node:fs/promises';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
const root=fileURLToPath(new URL('../',import.meta.url));
const revision='c2baacb8f4b441dd8505e63c2aeb5a1679b60b02';
const vendor=path.join(root,'native/vendor/RocketSim'), build=path.join(root,'native/.network-build');
const compiler=process.env.ARENA_EMXX || 'em++';
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
async function run(command,args){return await new Promise((resolve,reject)=>{
  let out='',err='';const child=spawn(command,args,{cwd:root,stdio:['ignore','pipe','pipe']});
  child.stdout.on('data',d=>out+=d);child.stderr.on('data',d=>err+=d);child.on('error',reject);
  child.on('exit',code=>code===0?resolve(out):reject(Error(`${command} exited ${code}: ${err}`)));
});}
async function walk(directory){let results=[];for(const e of await fs.readdir(directory,{withFileTypes:true})){
  if(e.name==='.git')continue;const p=path.join(directory,e.name);if(e.isDirectory())results.push(...await walk(p));else results.push(p);
}return results.sort();}
try{await fs.access(vendor);}catch{
  await fs.mkdir(vendor,{recursive:true});await run('git',['init',vendor]);
  await run('git',['-C',vendor,'remote','add','origin','https://github.com/ZealanL/RocketSim.git']);
  await run('git',['-C',vendor,'fetch','--depth=1','origin',revision]);await run('git',['-C',vendor,'checkout','--detach','FETCH_HEAD']);
}
const files=await walk(vendor);let checks='';for(const p of files)checks+=path.relative(vendor,p).replaceAll(path.sep,'/')+' '+hash(await fs.readFile(p))+'\n';
if(files.length!==275||hash(checks)!=='d41b5a815537971c4ab04dc3aac950a7866a695b18e77f99f331b90fd4e0f37c')throw Error('Pinned vendor source mismatch; no build accepted');
const bridge=gunzipSync(await fs.readFile(path.join(root,'native/bridge.cpp.gz')));
if(hash(bridge)!=='e67a6967c366065e7345753a0e0adb4b0420e53f74e61bb6c37cd07a8b1151d8')throw Error('Recovered original application bridge mismatch');
await fs.writeFile(path.join(root,'native/bridge.cpp'),bridge);
const version=await run(compiler,['--version']);if(!/\b4\.0\.10\b/.test(version))throw Error('Use the pinned Emscripten 4.0.10 SDK');
await fs.mkdir(build,{recursive:true});
const sources=[path.join(root,'native/network-state.cpp'),...files.filter(p=>p.endsWith('.cpp'))];
const flags=['-std=c++20','-O2','-fexceptions','-DRS_DONT_LOG','-DNDEBUG'];
const objects=sources.map((_,i)=>path.join(build,`${i}.o`));
let cursor=0,finished=0;
await Promise.all(Array.from({length:3},async()=>{while(cursor<sources.length){const i=cursor++;
  await run(compiler,[...flags,'-c',sources[i],'-o',objects[i]]);
  if(++finished%20===0)console.log(`Compiled ${finished}/${sources.length}`);
}}));
const directory=path.join(root,'public/physics');await fs.mkdir(directory,{recursive:true});
await run(compiler,[...flags,...objects,'-o',path.join(directory,'rocketsim-network.js'),
 '-sMODULARIZE=1','-sEXPORT_ES6=1','-sEXPORT_NAME=createRocketSim','-sENVIRONMENT=web,node',
 '-sALLOW_MEMORY_GROWTH=1','-sINITIAL_MEMORY=33554432','-sMAXIMUM_MEMORY=268435456',
 '-sEXPORTED_RUNTIME_METHODS=["HEAPU8","HEAP32","HEAPF32","HEAPF64"]','-sSTACK_SIZE=2097152',
 '-sDISABLE_EXCEPTION_CATCHING=0','-sEXPORTED_FUNCTIONS=["_malloc","_free"]']);
const wasmSha256=hash(await fs.readFile(path.join(directory,'rocketsim-network.wasm')));
const manifest={schema:1,checkpointVersion:1,revision,emscripten:'4.0.10',wasmSha256,
 loaderSha256:hash(await fs.readFile(path.join(directory,'rocketsim-network.js'))),
 bridgeSha256:hash(bridge),extensionSha256:hash(await fs.readFile(path.join(root,'native/network-state.cpp'))),
 vendorDigest:hash(checks),baseline:'4d3b9c9f2c2227bc72d292fb5f294ab1f435e34b8ac8300527ee9d833a829405',
 scope:'Exposed Soccar gameplay checkpoint; not Bullet solver/manifold serialization. Offline core unchanged.'};
await fs.writeFile(path.join(directory,'rocketsim-network-build.json'),JSON.stringify(manifest,null,2)+'\n');
await fs.writeFile(path.join(root,'src/physics/network-core.js'),`// Generated by the pinned online-core build.\nexport const NETWORK_CHECKPOINT_VERSION = 1;\nexport const NETWORK_CORE_SHA256 = '${wasmSha256}';\n`);
console.log(JSON.stringify(manifest,null,2));
